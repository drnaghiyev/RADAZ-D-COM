import assert from 'node:assert/strict';
import {loadTypeScript} from './load-typescript.mjs';
const output=loadTypeScript('lib/anatomy-volume.ts');
const {volumeLabelAt,sampleAnatomyPlane,volumeAnatomyName}=output;
const c=Math.SQRT1_2;
const geometry={dimensions:[7,6,5],spacing:[.8,1.7,3.2],origin:[-88,31,-120],direction:[c,c,0,-c,c,0,0,0,1],modality:'CT'};
const mask=Uint8Array.from({length:7*6*5},(_,i)=>i%117+1);
const result={...geometry,mask};
const world=(x,y,z)=>geometry.origin.map((v,i)=>v+x*.8*geometry.direction[i]+y*1.7*geometry.direction[i+3]+z*3.2*geometry.direction[i+6]);
for(let z=0;z<5;z++)for(let y=0;y<6;y++)for(let x=0;x<7;x++)assert.equal(volumeLabelAt(result,world(x,y,z)),mask[(z*6+y)*7+x]);
assert.equal(volumeLabelAt(result,world(-1,0,0)),0);
assert.equal(volumeLabelAt(result,world(7,0,0)),0);
assert.deepEqual([...sampleAnatomyPlane(result,world(0,0,2),world(1,0,2),world(0,1,2),7,6)],[...mask.slice(84,126)]);
const coronal=sampleAnatomyPlane(result,world(0,3,4),world(1,3,4),world(0,3,3),7,5);
for(let z=0;z<5;z++)for(let x=0;x<7;x++)assert.equal(coronal[z*7+x],mask[((4-z)*6+3)*7+x]);
assert.match(volumeAnatomyName('kidney_left')[0],/^Sol/);
assert.match(volumeAnatomyName('rib_right_12')[0],/Sağ.*12/);
assert.match(volumeAnatomyName('vertebrae_C7')[0],/Boyun.*C7/);
console.log('PASS: oblique patient coordinates, anisotropic voxels, axial/coronal planes, bounds and side-specific names');
